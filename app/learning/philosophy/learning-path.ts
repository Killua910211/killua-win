export type ResolvedPathStep = PathStep & { node: PhilosophyNode; order: number };

export function resolvePath(path: LearningPath): ResolvedPathStep[] {
  return path.steps.map((step, index) => {
    const node = getNodeById(step.nodeId);
    if (!node) {
      throw new Error(`学习路径「${path.id}」第 ${index + 1} 步指向了不存在的节点：${step.nodeId}`);
    }
    return { ...step, node, order: index + 1 };
  });
}
