import { getNodeById, philosophyNodes, type PhilosophyNode } from './tree';

/**
 * 推荐基础学习路径。
 *
 * 这不是「哲学的正确学习顺序」——不存在这种东西。它解决的是另一个问题：
 * 「我什么都不知道，该从哪里开始？」
 *
 * 设计约束：
 *   - 每一步都必须是知识库里已经存在、且真的读得下去的条目；
 *   - 每一步都要说清它为下一步准备了什么，否则就只是一份目录；
 *   - 它属于知识地图，不是 Coursera 式课程，页面上不出现进度、打卡或完成度。
 */

export type PathStep = {
  nodeId: string;
  /** 这一步在整条路线里承担什么。 */
  why: string;
  /** 读完带走的东西。具体到能被检验，不写「加深理解」。 */
  brings: string;
  /** 它为下一步准备了什么。最后一步写这条路线之后可以往哪走。 */
  prepares: string;
};

/**
 * 主线之外的去处。
 *
 * 主线只走十一步，而核心问题有二十三个。原来的页面对剩下那十二个一字未提，
 * 读者走完之后只能回目录自己猜。这一层把它们按「你关心什么」分组，并逐条
 * 写明它默认你已经读过哪一步——这样它既不是第二条主线，也不是一份目录副本。
 */
export type PathBranch = {
  label: string;
  intro: string;
  entries: {
    nodeId: string;
    /** 什么样的关心会把人带到这一篇。 */
    forWho: string;
    /** 它默认你已经有的那个区分，以及在主线的第几步给出。 */
    needs: string;
  }[];
};

