export function getStudyGuide(nodeId: string): StudyGuide | undefined {
  return studyGuides[nodeId];
}

/**
 * 构建期校验：positionArguments 的键必须真的是该条目在 data.json 里的立场名。
 *
 * 这条校验是本轮加的。旧结构按数组下标把论证路径对齐到立场，没有任何检查，
 * 于是「修身与解脱」（现名「修养取向」）下面渲染出了当代福祉理论的论证，另一页写了三条路径而
 * 该页只有两个立场。键名对不上现在会在构建期直接失败。
 */
for (const [nodeId, guide] of Object.entries(studyGuides)) {
  if (!guide.positionArguments) continue;
  const node = getNodeById(nodeId);
  if (!node) {
    throw new Error(`精读层挂在不存在的节点上：${nodeId}`);
  }
  const names = new Set((node.positions ?? []).map((position) => position.name));
  for (const key of Object.keys(guide.positionArguments)) {
    if (!names.has(key)) {
      throw new Error(
        `${nodeId} 的论证路径键名「${key}」不是该条目的立场名。现有立场：${[...names].join('、') || '（无）'}`,
      );
    }
  }
}
