const experimentByNode = new Map<string, ThoughtExperiment>();

for (const experiment of thoughtExperiments) {
  if (!getNodeById(experiment.nodeId)) {
    throw new Error(`思想实验挂在不存在的节点上：${experiment.nodeId}`);
  }
  if (experimentByNode.has(experiment.nodeId)) {
    throw new Error(`一个条目只能有一个思想实验：${experiment.nodeId}`);
  }
  if (experiment.variations.length === 0) {
    throw new Error(`思想实验 ${experiment.nodeId} 没有变量改动，就不是思想实验`);
  }
  if (experiment.origin !== '本站原创案例' && !experiment.originNote) {
    throw new Error(`非原创的思想实验必须写明改写自什么：${experiment.nodeId}`);
  }
  // 人格标签的机械防线。它拦不住所有写法，但能拦住最容易滑过去的那几种。
  for (const word of labelWords) {
    if (experiment.closing.includes(word)) {
      throw new Error(`思想实验 ${experiment.nodeId} 的收尾在给读者贴立场标签：${word}`);
    }
  }
  experimentByNode.set(experiment.nodeId, experiment);
}

export function getThoughtExperiment(nodeId: string): ThoughtExperiment | undefined {
  return experimentByNode.get(nodeId);
}
