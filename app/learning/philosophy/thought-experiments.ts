/**
 * 思想实验。
 *
 * 目的只有一个：通过改变条件，把一个判断背后没说出口的原则逼出来。
 *
 * 它不是心理测试。任何形式的「根据你的回答，你是相容论者」都不允许出现——
 * 那是给人贴标签，不是让人看见自己在依据什么判断。正确的收尾是继续提问：
 * 「这一判断更看重控制条件」「如果坚持这个判断，还需要解释……」。
 */

export type ExperimentOrigin = '本站原创案例' | '教学重构' | '文献案例';

export type ExperimentScene = {
  /** 情境标签，例如「情境 A」。 */
  label: string;
  /** 只描述事实，不暗示应有的判断。 */
  scenario: string;
  /** 追问。问题本身不能预设答案。 */
  questions: string[];
};

export type ExperimentVariation = ExperimentScene & {
  /** 相对上一情境，改动的是哪一个变量。 */
  changed: string;
  /** 这次改动在检验什么条件。 */
  tests: string;
};

export type JudgementPrinciple = {
  /** 例如「控制能力」「可预见性」「自我塑造责任」。 */
  name: string;
  /** 如果读者的判断随这个变量变化，说明他实际上在依据什么。 */
  note: string;
};

export type ThoughtExperiment = {
  nodeId: string;
  title: string;
  /** 这个实验要暴露哪一个隐含原则。一句话。 */
  purpose: string;
  /** 案例的来历。原创例子不能伪装成文献案例，反过来也不行。 */
  origin: ExperimentOrigin;
  /** 文献案例或教学重构要说明改写自什么。原创案例留空。 */
  originNote?: string;
  base: ExperimentScene;
  variations: ExperimentVariation[];
  principles: JudgementPrinciple[];
  /** 收尾。只能继续提问或指出理论代价，不能给读者定性。 */
  closing: string;
  sources?: LedgerSource[];
};

