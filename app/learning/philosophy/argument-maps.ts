/**
 * 论证地图。
 *
 * 「A 认为 X，B 认为 Y」是立场表，不是论证。论证地图要回答的是：
 * A 凭哪几步走到 X，B 到底反对其中哪一步。
 *
 * 只给真正有明确论证结构的条目建图。哲学家介绍、历史背景和传统概览没有
 * 单一论证骨架，硬套只会把内容扭曲成图的形状。
 */

export type ArgumentStepKind = '前提' | '推论' | '分歧点';

export type ArgumentStep = {
  kind: ArgumentStepKind;
  text: string;
  /** 这一步为什么可以走，或它悄悄假设了什么。可省。 */
  note?: string;
  sourceIds?: string[];
};

export type ArgumentBranch = {
  /** 立场名，例如「不相容论」。 */
  name: string;
  /** 它在分歧点上选了哪一边，一句话。 */
  stance: string;
  /** 选定之后继续往下的推理。 */
  steps: string[];
  /**
   * `label` 让标签名实相符，默认是「反对」与「回应」。
   *
   * 这两个默认值曾经在传达错误信息。构成论分支下挂的泥块与雕像论证，做的是
   * 支持「构成不等于同一」，并没有回答上面那条反对（忒修斯之船是不对称分叉，
   * 凭什么结构与功能那条线索承载同一性）；顶着「回应」二字，读者会以为这条
   * 反对已经被答掉。同理，只提出竞争理由、要求对方为自己的优先地位辩护的，
   * 是「异议」而不是「反例」——后者要举出使某主张明显不成立的具体情形。
   * 遇到答非所问时，改标签并写明原反对留下什么，不要硬凑成闭环。
   */
  objection: { text: string; label?: string; sourceIds?: string[] };
  response: { text: string; label?: string; sourceIds?: string[] };
  /**
   * 接受这个立场要承担的理论代价。
   * 争议问题不给虚假结论：读者应看到分歧在哪、代价是什么，而不是被告知谁赢了。
   */
  cost: string;
};

export type ArgumentMap = {
  nodeId: string;
  title: string;
  /** 这张图在表达哪一条论证、不表达什么。避免读者把它当成整页的摘要。 */
  intro: string;
  /** 分歧之前的共同推理链。最后一步应当是分歧点。 */
  spine: ArgumentStep[];
  branches: ArgumentBranch[];
  /** 本图自己的来源。引用条目来源账里的编号时不必在这里重复。 */
  sources?: LedgerSource[];
};

/**
 * 本文件自带来源的核验约定。
 *
 * 标为 verified 的每一条，都是在 checkedOn 当天用脚本抓取整页、按 locator
 * 里写的小节标题定位、并读过该小节正文之后才写下的；locator 只写到实际读过
 * 的范围，没读到的小节不写进去。凡是推理步骤在来源里找不到对应文字的，都在
 * 该步的 note 或分支文字里标明它是教学性重构。
 */

const CHECKED_ON = '2026-09-11';

function verified(
  id: string,
  title: string,
  url: string,
  locator: string,
  supports: string,
  kind: LedgerSource['kind'] = '学术综述',
): LedgerSource {
  return { id, title, kind, url, locator, checked: 'verified', checkedOn: CHECKED_ON, supports };
}

