const argumentMapByNode = new Map<string, ArgumentMap>();

for (const map of argumentMaps) {
  if (argumentMapByNode.has(map.nodeId)) {
    throw new Error(`一个条目只能有一张论证地图：${map.nodeId}`);
  }
  if (!getNodeById(map.nodeId)) {
    throw new Error(`论证地图挂在不存在的节点上：${map.nodeId}`);
  }
  if (map.spine.at(-1)?.kind !== '分歧点') {
    throw new Error(`论证地图 ${map.nodeId} 的主干最后一步必须是分歧点`);
  }
  if (map.branches.length < 2) {
    throw new Error(`论证地图 ${map.nodeId} 至少要有两个分支，否则不存在分歧`);
  }
  argumentMapByNode.set(map.nodeId, map);
}

/**
 * 分支名在一张图内必须唯一：渲染层用它作为 React key。
 * 代价字段不能空着——争议问题不给虚假结论，靠的就是这一栏。
 */
for (const map of argumentMaps) {
  const names = new Set<string>();
  for (const branch of map.branches) {
    if (names.has(branch.name)) {
      throw new Error(`论证地图 ${map.nodeId} 里有重名分支：${branch.name}`);
    }
    names.add(branch.name);
    if (!branch.cost.trim()) {
      throw new Error(`论证地图 ${map.nodeId} 的分支「${branch.name}」没有写理论代价`);
    }
    if (branch.steps.length === 0) {
      throw new Error(`论证地图 ${map.nodeId} 的分支「${branch.name}」没有写推理步骤`);
    }
  }

  /** 自带来源标为已核验时必须留下核验日期，否则这个状态无法被复查。 */
  for (const source of map.sources ?? []) {
    if (source.checked === 'verified' && !source.checkedOn) {
      throw new Error(`论证地图 ${map.nodeId} 的来源 ${source.id} 标为已核验但没有核验日期`);
    }
  }
}

export function getArgumentMap(nodeId: string): ArgumentMap | undefined {
  return argumentMapByNode.get(nodeId);
}
