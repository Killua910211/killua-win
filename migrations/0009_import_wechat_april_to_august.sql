创作背景

吕蒙正出身贫寒，深刻体会穷人的苦难，所以读书勤奋、工作勤奋、爱民勤奋。

他年轻的时候，曾经和寇准一起在破窑读书，体会了人间冷暖。后来做了宰相，更体会到人心的宠辱，所以他写了一段《破窑赋》。

由于受传统观影响太深，有人认为吕蒙正的思想过于保守消极，因此吕蒙正的许多文章典籍都已失落，而在《吕文穆公传》中这首破窑赋被看作是吕蒙正的经典之作，相传当初是为教化太子而作此文的。

吕蒙正曾三次入相，兼任太子的老师，当时太子青春年少，目中无人，没有哪个太师敢当面教训太子。

吕蒙正决定写一篇文章，来告诫太子，于是写了这篇《破窑赋》。

这篇文章，虽然内容短小，但是却包含了无穷智慧，聪明的太子一下子就懂得其中的道理，据说太子读过此文后，一改常态，常虚心向他人请教。

个人心得

我分析这篇文章是近代人假托吕蒙正为了劝诫太子而创作的，以吕蒙正的语气自述从贫苦到富贵的经历，虽文章前后有逻辑混乱、例证有不合适或不实等诸多问题，但读起来依旧很“燃”，可秒杀当下很多鸡汤文。

比如逻辑混乱，“时也、运也、命也”强调宿命论，但又“心若不欺，必然扬眉吐气”，哪儿来的“必然”。

最近了解了一些关于基因科学、神经科学的东西，有些情绪和行为是由体内基因和分泌的物质决定，单看这一层也有宿命论的意思。

又看了一些强调理性注入的东西，辩驳一些基因科学和神经科学的“宿命论”。

简单来说，基因科学和神经科学只是像剥洋葱一样，只拨开了一小层皮，管理学、心理学等又拨开了一层。

人类作为一个洋葱还有无数层等待自我发掘和了解，目前的科学和技术了解的自己还远远不够。

以上的基因与理性，与本文某些观点一样，看似矛盾，但实际上可以根据《大数据时代》书所说“通过复杂相关关系看待问题、而不是简单的因果关系定结论”。

将矛盾的事物分开分别看待，“时、运、命”也有影响，但“事在人为”也需要，当分别看待后，这些都是有指导意义的。

颓废低落时，“时、运、命”，让自己豁达。
豁达之后，“事在人为”，努力做好自己。

最后“富贵不能淫，贫贱不能移，威武不能屈”：

对自己而言，自己富贵了也不要恃富而骄、尽情挥霍，自己贫贱了也不要灰心丧气、自暴自弃，自己得势之后也不要滥用强权、骄傲自满。

对他人而言，别人富贵了也不要阿谀谄媚、保持正直，别人贫贱了也不要百般欺辱、谦虚待人，别人得势了也不要趋炎附势，要坚持原则。

诚惶诚恐，保持敬畏。

